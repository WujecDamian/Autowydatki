import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createClient } from "@supabase/supabase-js";

// With SUPABASE_URL set, files go to a public Supabase Storage bucket.
// Without it (local development), they are written to server/uploads and served by the API.
const bucket = process.env.SUPABASE_BUCKET || "car-photos";

const supabase = process.env.SUPABASE_URL
  ? createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, {
      auth: { persistSession: false },
    })
  : null;

export const uploadsDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../uploads");
export const localUploadsRoute = "/api/uploads";

// Paths are generated by the server, never taken from a request.
export const saveFile = async (filePath, buffer, contentType) => {
  if (supabase) {
    const { error } = await supabase.storage
      .from(bucket)
      .upload(filePath, buffer, { contentType, upsert: false, cacheControl: "31536000, immutable" });

    if (error) {
      throw error;
    }

    return;
  }

  const target = path.join(uploadsDir, filePath);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, buffer);
};

export const removeFiles = async (filePaths) => {
  if (filePaths.length === 0) {
    return;
  }

  if (supabase) {
    const { error } = await supabase.storage.from(bucket).remove(filePaths);

    if (error) {
      throw error;
    }

    return;
  }

  await Promise.all(
    filePaths.map((filePath) => rm(path.join(uploadsDir, filePath), { force: true })),
  );
};

export const publicUrl = (filePath) =>
  supabase
    ? supabase.storage.from(bucket).getPublicUrl(filePath).data.publicUrl
    : `${localUploadsRoute}/${filePath}`;

// Every photo is stored as a full-size image plus a square thumbnail next to it.
export const thumbnailPath = (filePath) => filePath.replace(/\.webp$/, "-thumb.webp");

export const photoUrls = (storagePath) => ({
  url: publicUrl(storagePath),
  thumbUrl: publicUrl(thumbnailPath(storagePath)),
});
